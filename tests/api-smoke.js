'use strict';
const {spawn}=require('node:child_process');
const {mkdtempSync,readFileSync,readdirSync,statSync}=require('node:fs');
const {tmpdir}=require('node:os');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const binary=process.platform==='win32'?path.join(root,'JEUS_Lens_Windows_x64.exe'):path.join(root,'jeus-lens');
const temp=mkdtempSync(path.join(tmpdir(),'jeus-v5-api-'));
const child=spawn(binary,[],{cwd:root,env:{...process.env,JEUS_ANALYZER_NO_BROWSER:'1',JEUS_LENS_DATA_DIR:temp},stdio:['ignore','pipe','pipe']});
let log='';child.stdout.on('data',d=>log+=String(d));child.stderr.on('data',d=>process.stderr.write(d));
const delay=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
 let host;for(let i=0;i<100;i++){host=log.match(/http:\/\/127\.0\.0\.1:\d+\//)?.[0];if(host)break;await delay(100);}assert.ok(host,'server did not start');
 const origin=host.slice(0,-1),id='abcd12345678abcd12345678abcd1234';
 const text=readFileSync(path.join(__dirname,'sample_jeus.log'));
 const good=await fetch(host+`api/import?id=${id}&name=sample_jeus.log&encoding=utf-8`,{method:'POST',headers:{'Origin':origin,'Content-Type':'application/octet-stream'},body:text});
 if(good.status!==200)throw Error(`import ${good.status}: ${await good.text()}`);
 const summary=await good.json();
 assert.equal(summary.stats.all,8);assert.equal(summary.stats.sql,1);
 assert.equal(summary.storageMode,'metadata-only');
 const folders=readdirSync(path.join(temp,id));assert.deepEqual(folders.sort(),['index.bin','issues.bin','summary.json']);
 assert.equal(statSync(path.join(temp,id,'index.bin')).size,8*24);
 assert.equal(statSync(path.join(temp,id,'issues.bin')).size,8*8);
 assert.equal(summary.issueVersion,1);
 assert.ok(summary.hotspots?.length>0,'timestamped errors should create 5-minute hotspots');
 assert.equal(summary.hotspots[0].start,'2026-10-23 09:00');
 assert.equal(summary.hotspots[0].errors,2);
 assert.equal(summary.hotspots[0].sqlErrors,1);
 assert.ok(summary.issues.length>0);
 const selected=summary.issues[0];
 const issueResult=await fetch(host+'api/filter',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify({id,group:'issue:'+selected.id,query:''})});
 assert.equal(issueResult.status,200);assert.equal((await issueResult.json()).total,selected.count);
 const v=await fetch(host+`api/verify?id=${id}`,{method:'POST',headers:{Origin:origin,'Content-Type':'application/octet-stream'},body:text});if(v.status!==200)throw Error(`verify ${v.status}: ${await v.text()}`);
 const changed=Buffer.from(text);changed[42]=changed[42]===65?66:65;
 const invalid=await fetch(host+`api/verify?id=${id}`,{method:'POST',headers:{Origin:origin,'Content-Type':'application/octet-stream'},body:changed});assert.equal(invalid.status,409);
 const filtered=await fetch(host+'api/filter',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify({id,group:'sql:8',query:''})});
 assert.equal(filtered.status,200);const f=await filtered.json();assert.equal(f.total,1);
 const page=await fetch(host+`api/page?id=${id}&filterId=${f.filterId}&page=1`);assert.equal(page.status,200);const data=await page.json();assert.equal(data.rows.length,1);assert.equal(data.rows[0].sqlType,'기타 SQL');assert.equal(data.rows[0].index,3,'filtered page must preserve original event index for adjacent context');
 const archives=await (await fetch(host+'api/archives')).json();assert.equal(archives.items[0].id,id);
 console.log('BACKEND_IMPORT_VERIFY_FILTER_PAGE_HISTORY_PASS',JSON.stringify({events:summary.stats.all,sql:summary.stats.sql,bytes:summary.metadataBytes}));
})().catch(err=>{console.error(err);process.exitCode=1}).finally(()=>{child.kill('SIGTERM')});
